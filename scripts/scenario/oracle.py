"""Independent rational-arithmetic check, reading the preserved source, never TS.

Run: python3 scripts/scenario/oracle.py
Writes deterministic test fixtures and a compact numerical audit.
"""
from fractions import Fraction as F
from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parents[2]
source = (ROOT / 'docs/scenario/source/goal-objective.md').read_text()
source = source.split('## 1. District Dataset', 1)[1]
indicators = ['T1', 'T2', 'E1', 'E2', 'S1', 'S2', 'B1', 'B2', 'C1', 'C2']
rows = [[c.strip() for c in line.strip().strip('|').split('|')]
        for line in source.splitlines() if line.startswith('|')]
districts = [r for r in rows if r[0] in ['Esil', 'Almaty', 'Saryarka', 'Baikonur', 'Nura']]
baseline = {r[0].lower(): dict(zip(indicators, map(int, r[2:12]))) for r in districts}
population = {r[0].lower(): F(r[1]) for r in districts}
reported_districts = {r[0].lower(): F(r[12]) for r in districts}
weight_row = next(r for r in rows if r[0].startswith('wkw'))
weights = dict(zip(indicators, map(F, weight_row[1:])))
areas = {'Transport': 'transport', 'Environment': 'environment', 'Social Services': 'social',
         'Safety': 'safety', 'Municipal Services': 'municipal'}
catalogue = []
for r in rows:
    if re.fullmatch(r'M\d+', r[0]):
        effects = {k: int(v.replace('−', '-')) for k, v in re.findall(r'([TESBC][12])\s*([+−-]\d+)', r[6])}
        catalogue.append(dict(id=r[0], area=areas[r[1]], scope='district' if r[3] == 'District' else 'citywide',
                              cost=int(r[4]), lag=int(r[5]), effects=effects))
assert len(catalogue) == 14 and len(baseline) == 5 and sum(weights.values()) == sum(population.values()) == 1
by_id = {m['id']: m for m in catalogue}
# Independent transcription of the three fixed rules in source §2.
synergies = [('M1', 'M2', 'T1', 2), ('M10', 'M12', 'B1', 2), ('M5', 'M6', 'E2', 2)]

def assessment(values):
    scores = {d: sum(weights[k] * values[d][k] for k in indicators) for d in values}
    average = sum(population[d] * scores[d] for d in scores)
    minimum = min(scores.values())
    critical = [dict(districtId=d, indicatorId=k, value=values[d][k]) for d in values for k in indicators if values[d][k] < 40]
    return dict(districtScores=scores, cityAverage=average, weakestValue=minimum,
                weakestDistricts=[d for d in scores if scores[d] == minimum], criticalPairs=critical,
                finalScore=F(7, 10) * average + F(3, 10) * minimum - len(critical))

def evaluate(selections):
    values = {d: {k: F(v) for k, v in ks.items()} for d, ks in baseline.items()}
    selected = dict(selections)
    for mid, district in selections:
        m = by_id[mid]
        for d in ([district] if district else values):
            for k, v in m['effects'].items():
                values[d][k] += F(v * (8 - m['lag']), 8)
    for a, b, k, v in synergies:
        if a in selected and b in selected:
            values[selected[a]][k] += v
    values = {d: {k: max(F(0), min(F(100), v)) for k, v in ks.items()} for d, ks in values.items()}
    return dict(plan=[dict(initiativeId=m, scope='district', districtId=d) if d else
                      dict(initiativeId=m, scope='citywide') for m, d in selections],
                cost=sum(by_id[m]['cost'] for m, _ in selections), indicators=values, **assessment(values))

cases = {
    'sourceExample': [('M7', 'nura'), ('M8', 'nura'), ('M10', 'nura'), ('M12', None), ('M5', 'saryarka')],
    'lowCost': [('M9', 'nura'), ('M11', 'almaty'), ('M10', 'nura'), ('M12', None), ('M4', 'esil')],
    'negative': [('M4', 'esil'), ('M8', 'nura'), ('M11', 'almaty'), ('M12', None), ('M14', None)],
    'revision': [('M4', 'esil'), ('M8', 'nura'), ('M11', 'esil'), ('M12', None), ('M14', None)],
}
result = dict(baseline=baseline, population=population, weights=weights, catalogue=catalogue,
              baselineAssessment=assessment(baseline), cases={k: evaluate(v) for k, v in cases.items()})
def number(value):
    if isinstance(value, F): return float(value)
    raise TypeError(type(value))
encoded = json.dumps(result, default=number, indent=2, ensure_ascii=False)
(ROOT / 'tests/scenario-oracle.ts').write_text('// Generated by scripts/scenario/oracle.py from the preserved attachment.\nexport const oracle = ' + encoded + ' as const;\n')
b = result['baselineAssessment']; example = result['cases']['sourceExample']
lines = ['# Calculation audit', '', 'Generated independently with Python `fractions.Fraction` from the original technical specification tables. No production calculator is imported.', '',
         '| Claim | Source reports | Exact equation / data result | Status |', '| --- | ---: | ---: | --- |']
for d, claimed in reported_districts.items():
    actual = b['districtScores'][d]
    lines.append(f'| {d} baseline district score | {float(claimed)} | {float(actual)} | {"Agrees" if actual == claimed else "SOURCE DISCREPANCY"} |')
lines += [f'| Baseline city average | 56.86 | {float(b["cityAverage"])} | Agrees after display rounding |',
          f'| Baseline final score | 52.56 | {float(b["finalScore"])} | Agrees after display rounding |',
          f'| Example cost | 95 | {example["cost"]} | Agrees |',
          f'| Example score | ≈56.5 | {float(example["finalScore"])} | Source approximation; correct to 1 decimal |',
          f'| Example improvement | ≈4.0 | {float(example["finalScore"] - b["finalScore"])} | Source approximation; correct to 1 decimal |', '',
          'Equation: `0.7 × population-weighted district scores + 0.3 × minimum district score − count(values < 40)`. District scores use all ten supplied weights; each measure is multiplied by `(8 − lag) / 8`, then fixed synergies are added, then indicators clipped once.', '',
          f'Example: average **{float(example["cityAverage"])}**, weakest value **{float(example["weakestValue"])}**, critical pairs **{len(example["criticalPairs"])}**. The M10 + M12 bonus is +2 B1 in Nura.', '',
          'No inputs or coefficients were changed to fit source headlines. Unrounded values drive scoring and the strict threshold. The source example is a verification fixture, never a default or recommended plan.', '',
          'The source calls the 61-unit set “cheapest”. This work verifies its cost and validity with explicit districts; it does not conduct or claim an optimization proof.', '',
          'Reproduce: `python3 scripts/scenario/oracle.py`, then `npm test`. The generated fixture checks all 50 values and all assessment components for each case.']
(ROOT / 'docs/scenario/calculation-audit.md').write_text('\n'.join(lines) + '\n')
print(json.dumps(dict(baseline=float(b['finalScore']), example=float(example['finalScore']),
                     improvement=float(example['finalScore']-b['finalScore'])), indent=2))
